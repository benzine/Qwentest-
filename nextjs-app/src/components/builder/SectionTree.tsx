'use client';

import { useBuilderStore } from '@/store/useBuilderStore';
import { Section } from '@/types';

interface SectionTreeProps {
  sections: Section[];
}

export function SectionTree({ sections }: SectionTreeProps) {
  const { selectedSectionId, setSelectedSection, viewMode, setViewMode } = useBuilderStore();
  
  if (!sections || sections.length === 0) {
    return (
      <div className="p-4 text-gray-400 text-sm text-center">
        No sections yet. Click &quot;Add Section&quot; to get started.
      </div>
    );
  }
  
  return (
    <div className="py-2">
      {sections.map((section, index) => (
        <div
          key={section.id}
          onClick={() => {
            setSelectedSection(section.id);
            setViewMode('isolated-section');
          }}
          className={`group flex items-center px-4 py-3 cursor-pointer transition-colors border-l-2 ${
            selectedSectionId === section.id && viewMode === 'isolated-section'
              ? 'bg-gray-800 border-primary-500 text-white'
              : 'border-transparent text-gray-300 hover:bg-gray-800 hover:text-white'
          }`}
        >
          {/* Drag handle */}
          <span className="mr-3 text-gray-500 cursor-grab hover:text-gray-300">
            <svg className="w-4 h-4" fill="currentColor" viewBox="0 0 20 20">
              <path d="M7 2a2 2 0 1 0 .001 4.001A2 2 0 0 0 7 2zm0 6a2 2 0 1 0 .001 4.001A2 2 0 0 0 7 8zm0 6a2 2 0 1 0 .001 4.001A2 2 0 0 0 7 14zm6-8a2 2 0 1 0-.001-4.001A2 2 0 0 0 13 6zm0 2a2 2 0 1 0 .001 4.001A2 2 0 0 0 13 8zm0 6a2 2 0 1 0 .001 4.001A2 2 0 0 0 13 14z"/>
            </svg>
          </span>
          
          {/* Section icon based on type */}
          <span className="mr-3 text-gray-400">
            {getSectionIcon(section.type)}
          </span>
          
          {/* Section info */}
          <div className="flex-1 min-w-0">
            <div className="text-sm font-medium truncate">
              {section.adminLabel || `${section.type} ${index + 1}`}
            </div>
            <div className="text-xs text-gray-500">
              {section.modules.length} modules
            </div>
          </div>
          
          {/* Status indicators */}
          <div className="flex items-center space-x-2">
            {!section.isVisible && (
              <span className="text-gray-500" title="Hidden">
                <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M13.875 18.825A10.05 10.05 0 0112 19c-4.478 0-8.268-2.943-9.543-7a9.97 9.97 0 011.563-3.029m5.858.908a3 3 0 114.243 4.243M9.878 9.878l4.242 4.242M9.88 9.88l-3.29-3.29m7.532 7.532l3.29 3.29M3 3l3.59 3.59m0 0A9.953 9.953 0 0112 5c4.478 0 8.268 2.943 9.543 7a10.025 10.025 0 01-4.132 5.411m0 0L21 21" />
                </svg>
              </span>
            )}
            <span className="opacity-0 group-hover:opacity-100 transition-opacity">
              <svg className="w-4 h-4 text-gray-400 hover:text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 5l7 7-7 7" />
              </svg>
            </span>
          </div>
        </div>
      ))}
    </div>
  );
}

